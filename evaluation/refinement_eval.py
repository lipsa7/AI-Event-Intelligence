def _clean(value: Any) -> str:
    if value is None:
        return ""
    return " ".join(str(value).split()).strip()


def _key(value: Any) -> str:
    text = _clean(value).casefold()
    text = text.replace("-", "_").replace(" ", "_")
    text = re.sub(r"[^a-z0-9_]+", "", text)
    while "__" in text:
        text = text.replace("__", "_")
    return text.strip("_")


def _id(value: Any) -> str:
    return _clean(value).upper()


def _id_list(value: Any) -> List[str]:
    if value is None:
        return []

    if isinstance(value, str):
        value = [value]

    if not isinstance(value, (list, tuple, set)):
        return []

    out: List[str] = []
    seen: Set[str] = set()

    for item in value:
        if isinstance(item, Mapping):
            item = (
                item.get("evidence_id")
                or item.get("insight_id")
                or item.get("insight_revision_id")
                or item.get("id")
                or ""
            )

        normalized = _id(item)

        if normalized and normalized not in seen:
            seen.add(normalized)
            out.append(normalized)

    return out


def _string_list(value: Any) -> List[str]:
    if value is None:
        return []

    if isinstance(value, str):
        value = [value]

    if not isinstance(value, (list, tuple, set)):
        return []

    result = []
    seen = set()

    for item in value:
        normalized = _key(item)
        if normalized and normalized not in seen:
            seen.add(normalized)
            result.append(normalized)

    return result


def _safe_div(
    numerator: int | float,
    denominator: int | float,
) -> Optional[float]:
    if denominator == 0:
        return None
    return float(numerator) / float(denominator)


def _round(
    value: Optional[float],
    digits: int = 4,
) -> Optional[float]:
    if value is None:
        return None
    return round(float(value), digits)


def _mean(
    values: Sequence[float],
) -> Optional[float]:
    if not values:
        return None
    return sum(values) / len(values)


def _prf(
    predicted: Set[str],
    gold: Set[str],
) -> Dict[str, Optional[float]]:
    tp = len(predicted & gold)
    fp = len(predicted - gold)
    fn = len(gold - predicted)

    precision = _safe_div(tp, tp + fp)
    recall = _safe_div(tp, tp + fn)

    if (
        precision is None
        or recall is None
        or precision + recall == 0
    ):
        f1 = None
    else:
        f1 = (
            2.0
            * precision
            * recall
            / (
                precision
                + recall
            )
        )

    return {
        "tp": tp,
        "fp": fp,
        "fn": fn,
        "precision": _round(precision),
        "recall": _round(recall),
        "f1": _round(f1),
    }


def _contains_prohibited_private_reasoning(
    value: Any,
    path: str = "",
) -> Optional[str]:
    if isinstance(value, Mapping):
        for key, item in value.items():
            normalized = _key(key)
            current_path = f"{path}.{key}" if path else str(key)

            if normalized in PROHIBITED_PRIVATE_REASONING_FIELDS:
                return current_path

            nested = _contains_prohibited_private_reasoning(
                item,
                current_path,
            )

            if nested:
                return nested

    elif isinstance(value, (list, tuple)):
        for index, item in enumerate(value):
            nested = _contains_prohibited_private_reasoning(
                item,
                f"{path}[{index}]",
            )

            if nested:
                return nested

    return None


def _case_id(
    record: Mapping[str, Any],
) -> str:
    return _clean(
        record.get("case_id")
        or record.get("evaluation_id")
        or record.get("id")
    )


def load_jsonl(
    path: str | Path,
) -> List[Dict[str, Any]]:
    path = Path(path)
    rows: List[Dict[str, Any]] = []

    with path.open(
        "r",
        encoding="utf-8",
    ) as handle:
        for line_number, line in enumerate(handle, start=1):
            line = line.strip()

            if not line:
                continue

            try:
                payload = json.loads(line)
            except json.JSONDecodeError as exc:
                raise ValueError(
                    f"Invalid JSON at {path}:{line_number}: {exc}"
                ) from exc

            if not isinstance(payload, dict):
                raise ValueError(
                    f"{path}:{line_number} must be a JSON object."
                )

            rows.append(payload)

    return rows


def _index_cases(
    records: Sequence[Mapping[str, Any]],
    *,
    source_name: str,
) -> Dict[str, Dict[str, Any]]:
    indexed = {}

    for index, record in enumerate(records):
        if not isinstance(record, Mapping):
            raise ValueError(
                f"{source_name} record {index} must be an object."
            )

        case_id = _case_id(record)

        if not case_id:
            raise ValueError(
                f"{source_name} record {index} is missing case_id."
            )

        if case_id in indexed:
            raise ValueError(
                f"Duplicate {source_name} case_id={case_id!r}."
            )

        indexed[case_id] = dict(record)

    return indexed


def _quality_status(
    assessment: Any,
) -> str:
    if not isinstance(assessment, Mapping):
        return ""

    return _key(
        assessment.get("quality_status")
        or assessment.get("status")
    )


def _quality_score(
    assessment: Any,
) -> Optional[float]:
    if not isinstance(assessment, Mapping):
        return None

    value = assessment.get("quality_score")

    if value is None:
        return None

    try:
        numeric = float(value)
    except (TypeError, ValueError):
        return None

    if not 0.0 <= numeric <= 1.0:
        return None

    return numeric


