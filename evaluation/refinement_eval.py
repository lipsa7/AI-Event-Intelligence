def _aggregate_prf(
    cases: Sequence[Mapping[str, Any]],
    path: Sequence[str],
) -> Dict[str, Optional[float]]:
    tp = fp = fn = 0

    for case in cases:
        value: Any = case

        for key in path:
            if not isinstance(value, Mapping):
                value = {}
                break
            value = value.get(key, {})

        if not isinstance(value, Mapping):
            continue

        tp += int(value.get("tp", 0) or 0)
        fp += int(value.get("fp", 0) or 0)
        fn += int(value.get("fn", 0) or 0)

    precision = _safe_div(tp, tp + fp)
    recall = _safe_div(tp, tp + fn)

    if (
        precision is None
        or recall is None
        or precision + recall == 0
    ):
        f1 = None
    else:
        f1 = (
            2.0
            * precision
            * recall
            / (
                precision
                + recall
            )
        )

    return {
        "tp": tp,
        "fp": fp,
        "fn": fn,
        "precision": _round(precision),
        "recall": _round(recall),
        "f1": _round(f1),
    }


def _boolean_rate(
    cases: Sequence[Mapping[str, Any]],
    path: Sequence[str],
) -> Dict[str, Any]:
    values: List[bool] = []

    for case in cases:
        value: Any = case

        for key in path:
            if not isinstance(value, Mapping):
                value = None
                break
            value = value.get(key)

        if isinstance(value, bool):
            values.append(value)

    passed = sum(
        1
        for value in values
        if value
    )

    return {
        "labelled_count": len(values),
        "pass_count": passed,
        "rate": _round(
            _safe_div(
                passed,
                len(values),
            )
        ),
    }


def _numeric_mean(
    cases: Sequence[Mapping[str, Any]],
    path: Sequence[str],
) -> Optional[float]:
    values = []

    for case in cases:
        value: Any = case

        for key in path:
            if not isinstance(value, Mapping):
                value = None
                break
            value = value.get(key)

        if isinstance(value, (int, float)) and not isinstance(value, bool):
            values.append(float(value))

    return _round(
        _mean(values)
    )


def _tag_breakdown(
    cases: Sequence[Mapping[str, Any]],
) -> Dict[str, Any]:
    by_tag: Dict[
        str,
        List[Mapping[str, Any]],
    ] = defaultdict(list)

    for case in cases:
        for tag in case.get("case_tags", []):
            by_tag[tag].append(case)

    result = {}

    for tag, subset in sorted(by_tag.items()):
        result[tag] = {
            "case_count": len(subset),
            "refinement_decision_accuracy": _boolean_rate(
                subset,
                ("decision", "correct"),
            )["rate"],
            "weakness_targeting": _aggregate_prf(
                subset,
                ("targeting", "weaknesses"),
            ),
            "new_evidence": _aggregate_prf(
                subset,
                ("evidence", "new_evidence"),
            ),
            "acceptable_outcome_rate": _boolean_rate(
                subset,
                ("revision", "outcome_acceptable"),
            )["rate"],
            "quality_final_status_acceptance_rate": _boolean_rate(
                subset,
                ("quality", "final_status_acceptable"),
            )["rate"],
            "acceptable_stop_reason_rate": _boolean_rate(
                subset,
                ("stopping", "stop_reason_acceptable"),
            )["rate"],
        }

    return result


