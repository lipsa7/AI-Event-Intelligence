"""
Offline evaluation for the insight-refinement loop.

Recommended location:
    evaluation/refinement_eval.py

Purpose
-------
The refinement loop is intended to improve weak candidate insights without
silently lowering epistemic standards:

    StrategicInferenceAgent
            ↓
    initial candidate insight
            ↓
    InsightQualityService
            ↓
    structured weaknesses + refinement plan
            ↓
    EvidenceDiscoveryAgent / graph-context expansion
            ↓
    revised evidence/context
            ↓
    StrategicInferenceAgent refinement
            ↓
    Grounding / Red Team
            ↓
    refined insight or explicit stop/rejection

This evaluator measures whether refinement behaves correctly against a labelled
gold set.

It does NOT treat "higher quality score" as proof of truth.

Core questions
--------------
1. Did the system refine when refinement was warranted?
2. Did it target the right weaknesses?
3. Did it choose appropriate refinement actions?
4. Did it search for the right gap types?
5. Did it admit materially relevant new evidence?
6. Did the revision materially improve the insight when expected?
7. Did it preserve important counterevidence and uncertainty?
8. Did it avoid silent lifecycle mutation?
9. Did it stop correctly when there was no useful new evidence or no remaining
   budget?
10. Did it obey the compiled refinement policy?

Critical epistemic boundaries
-----------------------------
QUALITY SCORE
    != truth probability

REFINEMENT SUCCESS
    != factual correctness

NEW EVIDENCE
    != automatically stronger conclusion

A refinement may legitimately:
- strengthen an insight;
- narrow it;
- weaken it;
- rewrite it;
- leave it unchanged;
- reject it.

Gold JSONL
----------
One refinement case per line.

Example:

{
  "case_id": "REF-001",
  "case_tags": ["prospective", "counterevidence_required"],

  "should_refine": true,

  "expected_target_weaknesses": [
    "missing_counterevidence",
    "prospective_feasibility_unchecked"
  ],

  "acceptable_actions": [
    "retrieve_counterevidence",
    "broaden_evidence_search",
    "refine_reasoning"
  ],

  "required_actions": [
    "retrieve_counterevidence"
  ],

  "required_search_gap_types": [
    "counterevidence",
    "feasibility"
  ],

  "gold_new_evidence_ids": [
    "FACT-4",
    "COUNTER-1"
  ],

  "required_preserved_evidence_ids": [
    "FACT-1",
    "FACT-2"
  ],

  "required_preserved_counterevidence_ids": [
    "COUNTER-0"
  ],

  "required_critical_unknowns": [
    "Whether grid access outweighs tax and network advantages."
  ],

  "expected_material_change": true,

  "acceptable_refinement_outcomes": [
    "strengthened",
    "rewritten"
  ],

  "acceptable_stop_reasons": [
    "quality_threshold_met",
    "all_requested_gaps_resolved"
  ],

  "expected_initial_quality_status": "needs_refinement",
  "acceptable_final_quality_statuses": [
    "strong",
    "usable_with_limits"
  ],

  "minimum_quality_score_delta": 0.10,

  "expected_initial_epistemic_status": "unresolved",
  "acceptable_final_epistemic_statuses": [
    "partially_supported",
    "inference_supported"
  ],

  "max_refinement_rounds": 1
}

Prediction JSONL
----------------
The preferred prediction is a structured refinement trace generated by the
orchestrator / InsightTraceService:

{
  "case_id": "REF-001",

  "initial_insight": {...},
  "final_insight": {...},

  "initial_quality_assessment": {...},
  "final_quality_assessment": {...},

  "initial_grounding_assessment": {...},
  "final_grounding_assessment": {...},

  "refinement_plan": {
    "refinement_requested": true,
    "target_weaknesses": [...],
    "recommended_actions": [...],
    "search_gap_types": [...]
  },

  "refinement_rounds": [
    {
      "round_index": 0,
      "input_revision_id": "INSIGHTREV-001",
      "output_revision_id": "INSIGHTREV-002",
      "target_weaknesses": [...],
      "actions_taken": [...],
      "new_evidence_ids": [...],
      "outcome": "strengthened",
      "material_change": true,
      "stop_reason": "quality_threshold_met"
    }
  ],

  "evidence_before_ids": [...],
  "evidence_after_ids": [...],
  "counterevidence_before_ids": [...],
  "counterevidence_after_ids": [...],

  "stop_reason": "quality_threshold_met",
  "policy_snapshot": {
    "max_refinement_rounds": 1,
    "allowed_refinement_actions": [...]
  }
}

The evaluator also accepts several compatible field aliases.

Metrics
-------
Decision:
- refinement-decision accuracy;
- unnecessary-refinement rate;
- missed-refinement rate.

Targeting:
- weakness precision / recall / F1;
- required-action recall;
- unacceptable-action rate;
- search-gap-type precision / recall / F1.

Evidence:
- new-evidence precision / recall / F1;
- required-evidence preservation rate;
- required-counterevidence preservation rate.

Revision:
- expected material-change accuracy;
- text-change / revision-ID consistency;
- stable logical insight-ID preservation;
- acceptable outcome rate.

Quality:
- final-status acceptance rate;
- minimum-score-delta pass rate;
- mean quality-score delta;
- quality-regression rate.

Grounding:
- final epistemic-status acceptance rate;
- unresolved-to-supported transition rate when labelled;
- contradicted/unsupported regression rate.

Uncertainty:
- required critical-unknown preservation rate.

Stopping:
- acceptable stop-reason rate;
- no-new-evidence stop-decision accuracy when labelled.

Policy:
- refinement-round-limit violation rate;
- disallowed-action violation rate;
- release-authorization contamination rate;
- research-depth mutation rate;
- private-reasoning contamination rate.

Lifecycle:
- silent overwrite rate;
- stable logical identity preservation rate.

No paid service or web access is required.
No private chain-of-thought is required or stored.
"""

