# EvaluationRunner contract
# ---------------------------------------------------------------------------


def run_evaluation(
    gold_path: str | Path,
    predictions_path: str | Path | None = None,
    **kwargs: Any,
) -> Dict[str, Any]:
    """
    EvaluationRunner-compatible entry point.
    """
    if predictions_path is None:
        raise ValueError(
            "predictions_path is required for refinement evaluation."
        )

    return evaluate_predictions(
        load_jsonl(gold_path),
        load_jsonl(predictions_path),
    )


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------


def main(
    argv: Optional[Sequence[str]] = None,
) -> int:
    parser = argparse.ArgumentParser(
        description=(
            "Evaluate insight-refinement predictions against labelled gold."
        )
    )

    parser.add_argument(
        "--gold",
        required=True,
        help="Path to refinement_gold.jsonl",
    )
    parser.add_argument(
        "--predictions",
        required=True,
        help="Path to refinement prediction JSONL",
    )
    parser.add_argument(
        "--output",
        default="",
        help="Optional output JSON path",
    )

    args = parser.parse_args(argv)

    result = run_evaluation(
        args.gold,
        args.predictions,
    )

    if args.output:
        output_path = Path(args.output)
        output_path.parent.mkdir(
            parents=True,
            exist_ok=True,
        )
        output_path.write_text(
            json.dumps(
                result,
                ensure_ascii=False,
                indent=2,
                sort_keys=True,
            ),
            encoding="utf-8",
        )
    else:
        print(
            json.dumps(
                result,
                ensure_ascii=False,
                indent=2,
                sort_keys=True,
            )
        )

    return 0


if __name__ == "__main__":
    raise SystemExit(main())